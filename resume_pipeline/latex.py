"""Convert the pipeline's resume Markdown into a clean, ATS-friendly LaTeX file.

This is deterministic (no LLM call), so the .tex always matches the final resume exactly.
The template uses only standard TeX Live packages and compiles with pdflatex or on Overleaf.

Standalone use:
    python -m resume_pipeline.latex output/<run>/resume_final.md            # writes resume_final.tex
    python -m resume_pipeline.latex resume_final.md -o jane.tex --pdf --paper letter
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import List, Optional

PREAMBLE = r"""%% Generated by resume-pipeline. Compile with pdflatex (or upload to Overleaf).
\documentclass[10pt]{article}
\usepackage[%(paper)s,margin=0.6in]{geometry}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\IfFileExists{lmodern.sty}{\usepackage{lmodern}}{}
\usepackage[hidelinks]{hyperref}
\usepackage{enumitem}
\usepackage{titlesec}
\usepackage{xcolor}
\usepackage{microtype}
%% No fi/fl ligatures, so ATS text extraction keeps words like "Airflow" intact.
\DisableLigatures[f]{encoding = *, family = *}

%% Make the PDF text machine-readable for applicant tracking systems.
\input{glyphtounicode}
\pdfgentounicode=1

\pagestyle{empty}
\setlength{\parindent}{0pt}
\setlength{\parskip}{0pt}
\definecolor{accent}{HTML}{%(accent)s}

\titleformat{\section}{\large\bfseries\scshape\color{accent}}{}{0em}{}[\vspace{-6pt}\rule{\linewidth}{0.4pt}]
\titlespacing*{\section}{0pt}{10pt}{5pt}

\setlist[itemize]{leftmargin=1.2em, itemsep=1pt, topsep=1pt, parsep=0pt, label=\textbullet}

%% \resumeentry{Title}{Organisation / subtitle}{Dates or location}
\newcommand{\resumeentry}[3]{%%
  \par\vspace{5pt}\noindent\textbf{#1}\hfill{\small #3}%%
  \ifx&#2&\else\\{\itshape #2}\fi\par\vspace{1pt}}

\begin{document}
"""

_UNICODE = {
    "–": r"\textendash{}", "—": r"\textemdash{}", "‘": "`", "’": "'", "“": "``", "”": "''",
    "•": r"\textbullet{}", "·": r"\textperiodcentered{}", "…": r"\ldots{}",
    "→": r"$\rightarrow$", "←": r"$\leftarrow$", "≈": r"$\approx$", "×": r"$\times$",
    "≥": r"$\geq$", "≤": r"$\leq$", "₹": "INR~", " ": "~", " ": r"\,",
}
_SPECIAL = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
    "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    "<": r"\textless{}", "`": r"\textasciigrave{}", ">": r"\textgreater{}", "|": r"\textbar{}",
}

_INLINE = re.compile(
    r"\[(?P<ltext>[^\]]+)\]\((?P<lurl>[^)\s]+)\)"            # [text](url)
    r"|\*\*(?P<bold>.+?)\*\*"                                 # **bold**
    r"|(?<![\w*])\*(?P<ital>[^*\s][^*]*?)\*(?![\w*])"         # *italic*
    r"|(?P<email>[\w.+-]+@[\w-]+\.[\w.-]+)"                   # email
    r"|(?P<url>(?:https?://|www\.)[^\s,;)]+|(?:linkedin\.com|github\.com)/[^\s,;)]+)"
)


def escape(text: str) -> str:
    out = []
    for ch in text:
        if ch in _SPECIAL:
            out.append(_SPECIAL[ch])
        elif ch in _UNICODE:
            out.append(_UNICODE[ch])
        else:
            out.append(ch)
    return "".join(out)


def _href_url(u: str) -> str:
    u = u if u.startswith(("http://", "https://", "mailto:")) else "https://" + u
    return u.replace("\\", "/").replace("%", r"\%").replace("#", r"\#")


def inline(text: str) -> str:
    """Escape text for LaTeX while converting links, bold, italics, emails and URLs."""
    out, pos = [], 0
    for m in _INLINE.finditer(text):
        out.append(escape(text[pos:m.start()]))
        if m.group("ltext"):
            out.append(r"\href{%s}{%s}" % (_href_url(m.group("lurl")), inline(m.group("ltext"))))
        elif m.group("bold"):
            out.append(r"\textbf{%s}" % inline(m.group("bold")))
        elif m.group("ital"):
            out.append(r"\textit{%s}" % inline(m.group("ital")))
        elif m.group("email"):
            e = m.group("email")
            out.append(r"\href{mailto:%s}{%s}" % (e, escape(e)))
        else:
            u = m.group("url").rstrip(".")
            out.append(r"\href{%s}{%s}" % (_href_url(u), escape(u)))
            out.append(escape(m.group("url")[len(u):]))
        pos = m.end()
    out.append(escape(text[pos:]))
    return "".join(out)


def _entry(heading: str) -> str:
    """'Role | Company | Dates' -> \\resumeentry{Role}{Company}{Dates}."""
    parts = [p.strip() for p in re.split(r"\s+[|·•]\s+", heading) if p.strip()]
    clean = [p.strip("*") for p in parts]
    if len(clean) == 1:
        title, sub, right = clean[0], "", ""
    elif len(clean) == 2:
        # 'Role | Dates' puts the second part on the right; 'Role | Company' puts it underneath.
        if re.search(r"\d|present|current|now", clean[1], re.I):
            title, sub, right = clean[0], "", clean[1]
        else:
            title, sub, right = clean[0], clean[1], ""
    else:
        title, right, sub = clean[0], clean[-1], ", ".join(clean[1:-1])
    return r"\resumeentry{%s}{%s}{%s}" % (inline(title), inline(sub), inline(right))


def markdown_to_latex(markdown: str, paper: str = "a4paper", accent: str = "1F3A5F") -> str:
    body: List[str] = []
    in_list = False
    seen_name = seen_section = center_open = False
    header_lines: List[str] = []

    def close_list() -> None:
        nonlocal in_list
        if in_list:
            body.append(r"\end{itemize}")
            in_list = False

    def flush_header() -> None:
        nonlocal center_open
        if not center_open:
            return
        if header_lines:
            pieces: List[str] = []
            for ln in header_lines:
                pieces += [p.strip() for p in re.split(r"\s+[|·•]\s+|\s{2,}", ln) if p.strip()]
            body.append(r"{\small " + r"\enspace\textbar{}\enspace ".join(inline(p) for p in pieces) + "}")
            header_lines.clear()
        body.append(r"\end{center}")
        center_open = False

    for raw in markdown.splitlines():
        s = raw.strip()
        if not s or s in ("---", "***", "___"):
            close_list()
            continue
        if s.startswith("# ") and not seen_name:
            seen_name = center_open = True
            body.append(r"\begin{center}")
            body.append(r"{\LARGE\bfseries %s}\\[3pt]" % inline(s[2:].strip()))
            continue
        if s.startswith("## "):
            close_list()
            flush_header()
            seen_section = True
            body.append(r"\section*{%s}" % inline(s[3:].strip()))
            continue
        if s.startswith("### "):
            close_list()
            body.append(_entry(s[4:].strip()))
            continue
        if s.startswith(("- ", "* ", "+ ")):
            if not in_list:
                body.append(r"\begin{itemize}")
                in_list = True
            body.append(r"  \item " + inline(s[2:].strip()))
            continue
        close_list()
        if seen_name and not seen_section:
            header_lines.append(s)  # contact line(s) under the name
        else:
            body.append(inline(s) + r"\par\vspace{2pt}")

    close_list()
    flush_header()

    return PREAMBLE % {"paper": paper, "accent": accent} + "\n".join(body) + "\n\\end{document}\n"


def write_latex(markdown: str, tex_path: Path, paper: str = "a4paper", pdf: bool = False) -> Optional[Path]:
    """Write the .tex file; if pdf=True and pdflatex is installed, also build a PDF next to it.

    Returns the PDF path if one was built, else None.
    """
    tex_path.write_text(markdown_to_latex(markdown, paper=paper), encoding="utf-8")
    if not pdf:
        return None
    return compile_pdf(tex_path)


def compile_pdf(tex_path: Path) -> Optional[Path]:
    exe = shutil.which("pdflatex")
    if not exe:
        print("pdflatex not found; skipping PDF build (upload the .tex to Overleaf instead).", file=sys.stderr)
        return None
    with tempfile.TemporaryDirectory() as tmp:
        proc = subprocess.run([exe, "-interaction=nonstopmode", "-halt-on-error", "-output-directory", tmp, str(tex_path)],
                              capture_output=True, text=True, timeout=120)
        built = Path(tmp) / (tex_path.stem + ".pdf")
        if proc.returncode != 0 or not built.exists():
            tail = "\n".join(proc.stdout.splitlines()[-15:])
            print(f"pdflatex failed for {tex_path}:\n{tail}", file=sys.stderr)
            return None
        out = tex_path.with_suffix(".pdf")
        shutil.copy(built, out)
        return out


def main(argv: Optional[List[str]] = None) -> None:
    ap = argparse.ArgumentParser(prog="python -m resume_pipeline.latex",
                                 description="Convert a resume Markdown file to LaTeX.")
    ap.add_argument("markdown", help="Resume .md file (e.g. output/<run>/resume_final.md)")
    ap.add_argument("-o", "--output", help="Output .tex path (default: same name, .tex)")
    ap.add_argument("--paper", choices=["a4", "letter"], default="a4")
    ap.add_argument("--pdf", action="store_true", help="Also compile to PDF (needs pdflatex)")
    a = ap.parse_args(argv)

    src = Path(a.markdown)
    out = Path(a.output) if a.output else src.with_suffix(".tex")
    pdf = write_latex(src.read_text(encoding="utf-8"), out, paper=f"{a.paper}paper", pdf=a.pdf)
    print(f"LaTeX: {out}")
    if pdf:
        print(f"PDF:   {pdf}")


if __name__ == "__main__":
    main()
